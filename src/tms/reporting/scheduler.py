"""Stores reports and creates the scheduled ones (TMS-F-017): when a day, week or month ends the report for it is
generated by itself and is then available to download."""
from __future__ import annotations

import json
from datetime import datetime

from sqlalchemy import select
from sqlalchemy.orm import Session

from tms.common import clock
from tms.common.errors import NotFoundError
from tms.reporting import generator
from tms.reporting.models import Report

_last_checked: datetime | None = None


def meta(report: Report) -> dict:
    return {"id": report.id, "period": report.period, "periodStart": report.period_start.isoformat(),
            "periodEnd": report.period_end.isoformat(), "generatedAt": report.generated_at.isoformat(),
            "generatedBy": report.generated_by}


def generate(db: Session, period: str, start: datetime, end: datetime, generated_by: str,
             now: datetime | None = None) -> Report:
    """Create the report for a period, or refresh it if it already exists."""
    now = now or clock.now()
    content = json.dumps(generator.build(db, period, start, end, now))
    report = db.scalar(select(Report).where(Report.period == period, Report.period_start == start))
    if report is None:
        report = Report(period=period, period_start=start, period_end=end, generated_at=now,
                        generated_by=generated_by, content=content)
        db.add(report)
    else:
        report.content, report.generated_at, report.generated_by = content, now, generated_by
    db.commit()
    return report


def run_due(db: Session, now: datetime | None = None) -> list[Report]:
    """Generate the report for the most recently finished day, week and month if it is missing."""
    now = now or clock.now()
    created = []
    for period in generator.PERIODS:
        start, end = generator.last_completed(period, now)
        if db.scalar(select(Report.id).where(Report.period == period, Report.period_start == start)) is None:
            created.append(generate(db, period, start, end, "scheduler", now))
    return created


def run_due_throttled(db: Session, now: datetime) -> list[Report]:
    """For the background loop: look at most once a minute."""
    global _last_checked
    if _last_checked is not None and (now - _last_checked).total_seconds() < 60:
        return []
    _last_checked = now
    return run_due(db, now)


def get(db: Session, report_id: int) -> Report:
    report = db.get(Report, report_id)
    if report is None:
        raise NotFoundError(f"Report {report_id} does not exist", code="report_not_found")
    return report


def list_reports(db: Session, period: str | None = None, limit: int = 100) -> list[dict]:
    query = select(Report).order_by(Report.period_start.desc(), Report.id.desc()).limit(limit)
    if period:
        query = query.where(Report.period == period)
    return [meta(r) for r in db.scalars(query)]
